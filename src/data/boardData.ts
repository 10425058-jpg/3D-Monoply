export interface SpaceTransform {
  position: [number, number, number];
  rotationY: number;
  width: number;
  depth: number;
  isCorner: boolean;
  innerStripDirection: [number, number, number]; // Vector pointing toward board center
}

/**
 * Computes the exact 3D world position, dimensions, and rotation for each of the 40 spaces.
 * Total board size is 22 x 22 units.
 * Corners are 2.9 x 2.9 units; regular spaces are 1.8 x 2.9 units (9 * 1.8 + 2 * 2.9 = 22.0).
 */
export function getSpaceTransform(id: number): SpaceTransform {
  const cornerSize = 2.9;
  const edgeWidth = 1.8;
  const edgeDepth = 2.9;
  const cornerCenter = 11 - cornerSize / 2; // 9.55

  if (id === 0) {
    return {
      position: [cornerCenter, 0, cornerCenter],
      rotationY: 0,
      width: cornerSize,
      depth: cornerSize,
      isCorner: true,
      innerStripDirection: [-1, 0, -1],
    };
  }
  if (id > 0 && id < 10) {
    const idx = id - 1;
    const x = 7.2 - idx * edgeWidth;
    return {
      position: [x, 0, cornerCenter],
      rotationY: 0,
      width: edgeWidth,
      depth: edgeDepth,
      isCorner: false,
      innerStripDirection: [0, 0, -1],
    };
  }
  if (id === 10) {
    return {
      position: [-cornerCenter, 0, cornerCenter],
      rotationY: -Math.PI / 2,
      width: cornerSize,
      depth: cornerSize,
      isCorner: true,
      innerStripDirection: [1, 0, -1],
    };
  }
  if (id > 10 && id < 20) {
    const idx = id - 11;
    const z = 7.2 - idx * edgeWidth;
    return {
      position: [-cornerCenter, 0, z],
      rotationY: -Math.PI / 2,
      width: edgeWidth,
      depth: edgeDepth,
      isCorner: false,
      innerStripDirection: [1, 0, 0],
    };
  }
  if (id === 20) {
    return {
      position: [-cornerCenter, 0, -cornerCenter],
      rotationY: Math.PI,
      width: cornerSize,
      depth: cornerSize,
      isCorner: true,
      innerStripDirection: [1, 0, 1],
    };
  }
  if (id > 20 && id < 30) {
    const idx = id - 21;
    const x = -7.2 + idx * edgeWidth;
    return {
      position: [x, 0, -cornerCenter],
      rotationY: Math.PI,
      width: edgeWidth,
      depth: edgeDepth,
      isCorner: false,
      innerStripDirection: [0, 0, 1],
    };
  }
  if (id === 30) {
    return {
      position: [cornerCenter, 0, -cornerCenter],
      rotationY: Math.PI / 2,
      width: cornerSize,
      depth: cornerSize,
      isCorner: true,
      innerStripDirection: [-1, 0, 1],
    };
  }
  // id 31..39
  const idx = id - 31;
  const z = -7.2 + idx * edgeWidth;
  return {
    position: [cornerCenter, 0, z],
    rotationY: Math.PI / 2,
    width: edgeWidth,
    depth: edgeDepth,
    isCorner: false,
    innerStripDirection: [-1, 0, 0],
  };
}
